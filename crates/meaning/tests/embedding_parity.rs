#[test]
fn scores_match_python_scores() {
    let model = installed_model();
    let scores = model.score(QUERY, &PASSAGES);
    assert_eq!(scores.len(), EXPECTED_SCORES.len());
    for (index, (actual, expected)) in scores.iter().zip(EXPECTED_SCORES).enumerate() {
        assert!(
            (actual - expected).abs() < 1e-5,
            "passage {index}: score {actual} != {expected}"
        );
    }
}

