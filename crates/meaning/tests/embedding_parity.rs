//! Parity with the frozen Model2Vec vectors and scores from the legacy encoder
//! on the pinned model. The model is not committed (29.5 MiB).
//! Run `pdf-goat setup meaning` before this suite; missing or invalid assets
//! fail the tests rather than skipping the comparisons.

use std::path::PathBuf;
use std::sync::LazyLock;

use pdf_meaning::Model;

fn home() -> PathBuf {
    match std::env::var_os("PDF_GOAT_HOME") {
        Some(home) => PathBuf::from(home),
        None => PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join(".pdf-goat"),
    }
}

fn installed_model() -> &'static Model {
    static MODEL: LazyLock<Model> = LazyLock::new(|| {
        pdf_meaning::load(&home()).unwrap_or_else(|error| {
            panic!("embedding parity requires `pdf-goat setup meaning`: {error}")
        })
    });
    &MODEL
}

fn cosine(a: &[f32], b: &[f32]) -> f64 {
    let dot: f64 = a
        .iter()
        .zip(b)
        .map(|(&x, &y)| f64::from(x) * f64::from(y))
        .sum();
    let norm = |v: &[f32]| v.iter().map(|&x| f64::from(x).powi(2)).sum::<f64>().sqrt();
    dot / (norm(a) * norm(b))
}

fn norm(v: &[f32]) -> f32 {
    v.iter().map(|&x| f64::from(x).powi(2)).sum::<f64>().sqrt() as f32
}

fn assert_passage(index: usize) {
    let model = installed_model();
    let rows = model.encode(&PASSAGES);
    let (actual, expected) = (&rows[index], &EXPECTED_VECTORS[index]);
    assert_eq!(actual.len(), 256);
    assert!(
        (norm(actual) - EXPECTED_NORMS[index]).abs() < 1e-5,
        "passage {index}: norm {} != {}",
        norm(actual),
        EXPECTED_NORMS[index]
    );
    if EXPECTED_NORMS[index] > 0.0 {
        let similarity = cosine(actual, expected);
        assert!(similarity > 0.9999, "passage {index}: cosine {similarity}");
    } else {
        assert!(
            actual.iter().all(|&x| x == 0.0),
            "passage {index}: expected a zero row"
        );
    }
}

